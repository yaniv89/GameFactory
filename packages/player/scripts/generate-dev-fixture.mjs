// Dev-only convenience: populates src/generated/{projectData,wasmBinaryBase64}.ts
// with a small fixture (the same shape src/smoke/smokeTest.ts's own
// fixture builds) so `vite build`/`vite dev` has something real to embed
// while iterating on this package locally, without needing the actual
// `forge export` CLI (M6 Phase 5e's own remaining piece) finished first.
// The real CLI generates these same two files from a real converted
// project — this script exists only so this package is independently
// testable before that lands.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const PACKAGE_ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const GENERATED_DIR = join(PACKAGE_ROOT, "src", "generated");

function readDialogueGuestBundle() {
  const path = require.resolve("@forge/dialogue/dist/guest-bundle.js", { paths: [PACKAGE_ROOT] });
  return readFileSync(path, "utf8");
}

function readWasmBase64() {
  const quickjsEmscriptenPkgJson = require.resolve("quickjs-emscripten/package.json", { paths: [PACKAGE_ROOT] });
  const wasmfilePkgJson = require.resolve("@jitl/quickjs-wasmfile-release-sync/package.json", {
    paths: [dirname(quickjsEmscriptenPkgJson)],
  });
  const wasmPath = join(dirname(wasmfilePkgJson), "dist", "emscripten-module.wasm");
  return readFileSync(wasmPath).toString("base64");
}

const GRID_WIDTH = 20;
const GRID_HEIGHT = 15;

function buildFixtureProjectData(guestBundleSource) {
  const tiles = new Array(GRID_WIDTH * GRID_HEIGHT).fill(1); // grass everywhere
  const playerStartX = 2;
  const playerStartY = 2;
  const WALL_TILE_ID = 4;
  for (let x = 5; x <= 8; x++) tiles[playerStartY * GRID_WIDTH + x] = WALL_TILE_ID; // a short wall to walk around

  return {
    projectId: "dev-fixture-project",
    buildId: "dev-fixture-build",
    schemaVersion: 1,
    engineVersion: "0.0.0-dev-fixture",
    scenes: [
      {
        id: "scene-1",
        name: "Dev Fixture Scene",
        tiles,
        entities: [
          { id: "player", kind: "player-start", tileX: playerStartX, tileY: playerStartY },
          {
            id: "npc-1",
            kind: "npc",
            tileX: playerStartX + 3,
            tileY: playerStartY + 3,
            dialogue: { speaker: "Guard", text: "Halt! ...oh, it's just you. Carry on." },
          },
        ],
      },
    ],
    installedModules: [
      {
        name: "@forge/dialogue",
        version: "1.0.0",
        config: { trees: [{ id: "npc-1", nodes: [{ speaker: "Guard", text: "Halt! ...oh, it's just you. Carry on." }] }] },
        guestBundleSource,
      },
    ],
    startSceneId: "scene-1",
  };
}

mkdirSync(GENERATED_DIR, { recursive: true });

const projectData = buildFixtureProjectData(readDialogueGuestBundle());
writeFileSync(
  join(GENERATED_DIR, "projectData.ts"),
  `// AUTO-GENERATED by scripts/generate-dev-fixture.mjs — do not edit by hand.\n` +
    `import type { PlayerProjectData } from "../playerProjectData.js";\n\n` +
    `export const PROJECT_DATA: PlayerProjectData = ${JSON.stringify(projectData, null, 2)};\n`,
);

const wasmBase64 = readWasmBase64();
writeFileSync(
  join(GENERATED_DIR, "wasmBinaryBase64.ts"),
  `// AUTO-GENERATED by scripts/generate-dev-fixture.mjs — do not edit by hand.\n` +
    `export const WASM_BINARY_BASE64: string = ${JSON.stringify(wasmBase64)};\n`,
);

console.log(`generate-dev-fixture: wrote ${GENERATED_DIR}`);
